local NexusUI=require(game:GetService('ReplicatedStorage'):WaitForChild('NexusUI'):WaitForChild('Init'))
local window=NexusUI:CreateWindow({Title='NEXUS UI',Subtitle='PREMIUM INTERFACE / 1.0'})
local general=window:CreateTab({Name='General'})
local toggle=general:CreateToggle({Name='Show particles',Default=true,Callback=function(value) print('Particles:',value) end})
local slider=general:CreateSlider({Name='Volume',Min=0,Max=100,Step=1,Default=65,Callback=function(value) print('Volume:',value) end})
local dropdown=general:CreateDropdown({Name='Quality',Options={'Low','Medium','High','Ultra'},Default='High',Callback=function(value) print('Quality:',value) end})
general:CreateTextbox({Name='Profile name',Default='Player',Placeholder='Your name',Callback=function(value) print('Name:',value) end})
general:CreateButton({Name='Save profile',Callback=function()
	window:Notify({Title='Profile saved',Content='Your preferences are ready.',Type='Success',Duration=4})
end})
local appearance=window:CreateTab({Name='Appearance'})
appearance:CreateColorPicker({Name='Particle color',Default=Color3.fromRGB(0,191,255),Callback=function(color) print('Color:',color) end})
appearance:CreateButton({Name='Reset controls',Callback=function()
	toggle:Set(true); slider:Set(65); dropdown:Set('High')
end})
window:Notify({Title='Welcome to NexusUI',Content='Mouse and touch supported.',Type='Success'})
